"""Checks on a logical data model.

The SDK exports, loads and deploys an LDM the same way it does an analytics model, and
until now validated neither. The LDM is the half worth getting right first: everything in
the analytics model stands on it, so a reference that does not resolve here does not break
one object, it breaks every metric and visualization that reaches through the join.

Like the analytics-model checks, these answer from the files alone. An LDM is
self-contained by construction -- a dataset's references name other datasets in the same
model, and their sources name columns of those datasets -- so there is nothing here that
needs a server, and no inheritance to reason about.

What "a column of that dataset" means is the subtlety the whole module turns on, and it is
not "an attribute it declares": a composite key propagates, so a dataset can legitimately
be joined on, and grained by, a component that arrives through one of its own references.
Resolving against declared attributes alone reports ordinary joins as broken, which is how
a validator earns a reputation for crying wolf and gets switched off.
"""

from __future__ import annotations

from typing import TYPE_CHECKING, Any

from gooddata_sdk.catalog.validation.model import Finding, Severity

if TYPE_CHECKING:
    from gooddata_sdk.catalog.workspace.declarative_model.workspace.logical_model.ldm import CatalogDeclarativeModel


def _datasets(model: CatalogDeclarativeModel) -> list[Any]:
    return list(model.ldm.datasets) if model.ldm is not None else []


def _date_instances(model: CatalogDeclarativeModel) -> list[Any]:
    return list(model.ldm.date_instances or []) if model.ldm is not None else []


def _attribute_ids(dataset: Any) -> set[str]:
    return {attribute.id for attribute in (dataset.attributes or [])}


def _grain_ids(dataset: Any) -> set[str]:
    return {entry.id for entry in (dataset.grain or [])}


def _joinable_ids(dataset: Any) -> set[str]:
    """What another dataset may join to on this one: its attributes and its grain.

    The grain matters and is not a superset of the attributes. A dataset with a composite
    key can carry a grain entry it does not declare itself, because that component arrives
    through one of its own references: a lookup table may declare a single attribute of its
    own while being grained on that attribute *and* on a component reached through a
    reference to another dataset. Resolving joins against declared attributes alone reports
    those perfectly ordinary joins as broken -- on the model this was built against it
    turned twenty-two healthy joins into findings.
    """
    return _attribute_ids(dataset) | _grain_ids(dataset)


def check_dataset_references(model: CatalogDeclarativeModel) -> list[Finding]:
    """Joins that point at a dataset, or a column in one, that does not exist.

    Two levels, and the second is the one that is easy to get wrong by hand: a reference
    names a target dataset, and each of its sources names a *column in that target*. A
    source whose target exists in some other dataset still does not join -- so the source is
    resolved against the dataset the reference actually names, not against the whole model.

    A reference to a date instance is resolved against the date instances rather than the
    datasets, and its sources are not checked: a date dataset's fields are granularities
    generated by the platform, not attributes the model declares.
    """
    datasets = _datasets(model)
    by_id = {dataset.id: dataset for dataset in datasets}
    date_ids = {instance.id for instance in _date_instances(model)}
    findings: list[Finding] = []

    for dataset in datasets:
        for reference_index, reference in enumerate(dataset.references or []):
            target_id = reference.identifier.id
            location = f"datasets.{dataset.id}.references[{reference_index}]"

            if target_id in date_ids:
                continue
            target = by_id.get(target_id)
            if target is None:
                findings.append(
                    Finding(
                        severity=Severity.ERROR,
                        code="unresolved_dataset_reference",
                        message=(
                            f"dataset {dataset.id!r} references {target_id!r}, which is not a dataset "
                            f"or date instance in this model; the join cannot be made"
                        ),
                        object_id=dataset.id,
                        location=location,
                    )
                )
                continue

            available = _joinable_ids(target)
            for source_index, source in enumerate(reference.sources or []):
                if source.target.type == "date":
                    continue
                if source.target.id not in available:
                    findings.append(
                        Finding(
                            severity=Severity.ERROR,
                            code="unresolved_reference_source",
                            message=(
                                f"dataset {dataset.id!r} joins to {target_id!r} on {source.target.id!r}, "
                                f"which {target_id!r} does not declare"
                            ),
                            object_id=dataset.id,
                            location=f"{location}.sources[{source_index}]",
                        )
                    )
    return findings


def check_grain(model: CatalogDeclarativeModel) -> list[Finding]:
    """Grain entries naming an attribute that is reachable from nowhere.

    The grain states what makes a row unique, so an entry naming nothing means the platform
    cannot establish the dataset's identity.

    A grain entry does not have to be one of the dataset's own attributes. A composite key
    routinely includes a component that arrives through one of the dataset's references, so
    the entry is resolved against the dataset's attributes *and* those of everything it
    references directly. Requiring it to be locally declared reports ordinary composite
    keys as broken. Date entries are left alone: they name a date instance.
    """
    datasets = _datasets(model)
    by_id = {dataset.id: dataset for dataset in datasets}
    findings: list[Finding] = []
    for dataset in datasets:
        available = _attribute_ids(dataset)
        for reference in dataset.references or []:
            referenced = by_id.get(reference.identifier.id)
            if referenced is not None:
                available |= _joinable_ids(referenced)
        for index, entry in enumerate(dataset.grain or []):
            if entry.type == "date":
                continue
            if entry.id not in available:
                findings.append(
                    Finding(
                        severity=Severity.ERROR,
                        code="unresolved_grain",
                        message=(
                            f"dataset {dataset.id!r} has grain {entry.id!r}, which is neither one of its "
                            f"attributes nor reachable through any dataset it references"
                        ),
                        object_id=dataset.id,
                        location=f"datasets.{dataset.id}.grain[{index}]",
                    )
                )
    return findings


def check_duplicate_ldm_ids(model: CatalogDeclarativeModel) -> list[Finding]:
    """Ids repeated where they have to be unique.

    Dataset ids, and attribute, label and fact ids across the whole model: a metric names a
    label by id alone, with no dataset to disambiguate it, so two labels sharing an id make
    every reference to that id ambiguous.
    """
    findings: list[Finding] = []

    def report(code: str, kind: str, object_id: str, location: str) -> None:
        findings.append(
            Finding(
                severity=Severity.ERROR,
                code=code,
                message=f"more than one {kind} has id {object_id!r}; references to it are ambiguous",
                object_id=object_id,
                location=location,
            )
        )

    seen_datasets: set[str] = set()
    seen_fields: dict[str, tuple[str, str]] = {}
    for dataset in _datasets(model):
        if dataset.id in seen_datasets:
            report("duplicate_dataset_id", "dataset", dataset.id, f"datasets.{dataset.id}")
        seen_datasets.add(dataset.id)

        fields: list[tuple[str, str]] = [("attribute", attribute.id) for attribute in (dataset.attributes or [])]
        fields += [
            ("label", label.id) for attribute in (dataset.attributes or []) for label in (attribute.labels or [])
        ]
        fields += [("fact", fact.id) for fact in (dataset.facts or [])]
        for kind, field_id in fields:
            if field_id in seen_fields:
                report(f"duplicate_{kind}_id", kind, field_id, f"datasets.{dataset.id}")
            else:
                seen_fields[field_id] = (kind, dataset.id)
    return findings


def check_dataset_sources(model: CatalogDeclarativeModel) -> list[Finding]:
    """Datasets with no way to get their data.

    A dataset is backed either by a physical table or by SQL. One with neither is not
    loadable, and one with both is contradictory -- the platform would have to pick.
    """
    findings: list[Finding] = []
    for dataset in _datasets(model):
        has_table = dataset.data_source_table_id is not None
        has_sql = dataset.sql is not None
        if not has_table and not has_sql:
            findings.append(
                Finding(
                    severity=Severity.WARNING,
                    code="dataset_without_source",
                    message=(
                        f"dataset {dataset.id!r} declares neither a data source table nor SQL, "
                        f"so it has nothing to load from"
                    ),
                    object_id=dataset.id,
                    location=f"datasets.{dataset.id}",
                )
            )
        elif has_table and has_sql:
            findings.append(
                Finding(
                    severity=Severity.WARNING,
                    code="dataset_with_two_sources",
                    message=f"dataset {dataset.id!r} declares both a data source table and SQL",
                    object_id=dataset.id,
                    location=f"datasets.{dataset.id}",
                )
            )
    return findings


def validate_ldm(model: CatalogDeclarativeModel) -> list[Finding]:
    """Every logical-model check. Needs no server."""
    return (
        check_duplicate_ldm_ids(model)
        + check_dataset_references(model)
        + check_grain(model)
        + check_dataset_sources(model)
    )
