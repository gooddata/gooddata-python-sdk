#!/usr/bin/env python3
# (C) 2025 GoodData Corporation
"""Keep ``gooddata_sdk.__init__``'s lazy-import tables in sync with its ``TYPE_CHECKING`` block.

``gooddata_sdk/__init__.py`` re-exports its public API lazily (PEP 562), which needs a
name -> module mapping as data. Hand-maintaining ~250 string pairs alongside the real imports
would drift, and the drift would only show up at runtime.

So the ``if TYPE_CHECKING:`` block is the single source of truth: it holds ordinary
``from x import Y`` statements that IDEs autocomplete, refactorings rewrite and type checkers
verify. ``_LAZY_IMPORTS`` and ``__all__`` are generated from it by this script and must never be
edited by hand. Adding a public export therefore means adding one normal import, then running
``scripts/sync_lazy_imports.py --update``.

Without ``--update`` the script only reports drift and leaves the file alone. That is what
``tests/sdk/test_lazy_imports.py`` runs, so forgetting to regenerate fails CI with the command
to fix it rather than shipping an export that raises ``AttributeError`` at runtime.
"""

from __future__ import annotations

import argparse
import ast
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
TARGET = REPO_ROOT / "packages/gooddata-sdk/src/gooddata_sdk/__init__.py"

BEGIN = "# --- begin generated by scripts/sync_lazy_imports.py ---"
END = "# --- end generated by scripts/sync_lazy_imports.py ---"

PREAMBLE = """# Public name -> module that defines it, generated from the ``TYPE_CHECKING`` block above.
# Importing all of these at module level pulls in the whole SDK (every catalog service,
# declarative model and generated API model) even when the caller wants a single class, so they
# are resolved on first access instead (PEP 562). Do not edit by hand -- see the script.
"""


def collect_exports(source: str) -> dict[str, str]:
    """Read the public name -> module mapping out of the ``TYPE_CHECKING`` block.

    Args:
        source (str): Contents of ``gooddata_sdk/__init__.py``.

    Returns:
        dict[str, str]: Exported name mapped to the module it is imported from.

    Raises:
        SystemExit: If the ``TYPE_CHECKING`` block is missing, or an import cannot be represented.
    """
    tree = ast.parse(source)
    block = next(
        (
            node
            for node in tree.body
            if isinstance(node, ast.If) and isinstance(node.test, ast.Name) and node.test.id == "TYPE_CHECKING"
        ),
        None,
    )
    if block is None:
        sys.exit(f"{TARGET}: no `if TYPE_CHECKING:` block found")

    exports: dict[str, str] = {}
    for node in block.body:
        if not isinstance(node, ast.ImportFrom) or node.module is None:
            sys.exit(f"{TARGET}:{getattr(node, 'lineno', '?')}: only `from X import Y` is supported here")
        for alias in node.names:
            if alias.asname is not None:
                sys.exit(f"{TARGET}:{node.lineno}: aliased imports are not supported ({alias.name})")
            if alias.name in exports:
                sys.exit(f"{TARGET}:{node.lineno}: duplicate export {alias.name}")
            exports[alias.name] = node.module
    return exports


def render(exports: dict[str, str]) -> str:
    """Render the generated block for the given exports.

    Args:
        exports (dict[str, str]): Exported name mapped to its defining module.

    Returns:
        str: The block to place between the begin/end markers, markers included.
    """
    names = sorted(exports)
    mapping = "\n".join(f'    "{n}": "{exports[n]}",' for n in names)
    all_names = "\n".join(f'    "{n}",' for n in ["__version__", *names])
    return f"{BEGIN}\n{PREAMBLE}_LAZY_IMPORTS: dict[str, str] = {{\n{mapping}\n}}\n\n__all__ = [\n{all_names}\n]\n{END}"


def splice(source: str, block: str) -> str:
    """Replace the generated region of ``source`` with ``block``.

    Args:
        source (str): Current file contents.
        block (str): Rendered replacement, markers included.

    Returns:
        str: Updated file contents.

    Raises:
        SystemExit: If the begin/end markers are missing or out of order.
    """
    start, end = source.find(BEGIN), source.find(END)
    if start == -1 or end == -1 or end < start:
        sys.exit(f"{TARGET}: generated-block markers not found")
    return source[:start] + block + source[end + len(END) :]


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--update", action="store_true", help="rewrite the file instead of only reporting drift")
    args = parser.parse_args()

    source = TARGET.read_text()
    updated = splice(source, render(collect_exports(source)))
    if source == updated:
        return 0
    if not args.update:
        print(
            f"{TARGET}: _LAZY_IMPORTS/__all__ are out of sync with the TYPE_CHECKING block.\n"
            f"Run `scripts/sync_lazy_imports.py --update`.",
            file=sys.stderr,
        )
        return 1
    TARGET.write_text(updated)
    print(f"{TARGET}: regenerated _LAZY_IMPORTS/__all__")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
